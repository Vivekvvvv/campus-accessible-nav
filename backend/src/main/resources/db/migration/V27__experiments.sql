-- PR-18: A/B experiment platform
CREATE TABLE IF NOT EXISTS t_experiment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(64) NOT NULL UNIQUE,
  description VARCHAR(512),
  status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
  traffic_percent INT NOT NULL DEFAULT 100,
  variants_json TEXT NOT NULL DEFAULT '["control","treatment"]',
  config_json TEXT,
  tenant_id VARCHAR(32) NOT NULL DEFAULT 'default',
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS t_experiment_assignment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  experiment_id BIGINT NOT NULL REFERENCES t_experiment(id),
  user_id VARCHAR(64) NOT NULL,
  variant VARCHAR(64) NOT NULL,
  assigned_at TIMESTAMP NOT NULL DEFAULT NOW(),
  UNIQUE(experiment_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_experiment_status ON t_experiment (status);
CREATE INDEX IF NOT EXISTS idx_experiment_tenant ON t_experiment (tenant_id);
CREATE INDEX IF NOT EXISTS idx_experiment_assignment_user ON t_experiment_assignment (user_id);
CREATE INDEX IF NOT EXISTS idx_experiment_assignment_exp ON t_experiment_assignment (experiment_id);
